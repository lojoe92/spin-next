#!/usr/bin/env python3
"""Build helpers for Spin Next.

    python3 tools/build.py data      # data/*.json  -> docs/data/albums.js
    python3 tools/build.py android   # docs/        -> android/app/src/main/assets/
    python3 tools/build.py artifact  # docs/        -> dist/spin-next-artifact.html (single file for a Claude artifact)
    python3 tools/build.py all

docs/ is the website (served by GitHub Pages). Everything else is generated from it.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / 'docs'
DATA = ROOT / 'data'


def build_data():
    albums = json.loads((DATA / 'albums.json').read_text(encoding='utf8'))
    tags = json.loads((DATA / 'tags.json').read_text(encoding='utf8'))
    missing = [a[0] for a in albums if str(a[0]) not in tags]
    if missing:
        sys.exit(f'tags.json is missing ids: {missing[:10]}')
    out = DOCS / 'data' / 'albums.js'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        '// Generated by tools/build.py from data/albums.json and data/tags.json. Do not edit by hand.\n'
        '// ALBUMS row: [sheetRow, artist, title, year, genre, minutes, songs, english(1/0), edition(-1 removed, 1 added, 0), rating, reviewDate]\n'
        '// TAGS[id]: [styles, instruments, region, moods, description]\n'
        'const ALBUMS = ' + json.dumps(albums, ensure_ascii=False, separators=(',', ':')) + ';\n'
        'const TAGS = ' + json.dumps(tags, ensure_ascii=False, separators=(',', ':')) + ';\n',
        encoding='utf8')
    print(f'wrote {out.relative_to(ROOT)} ({len(albums)} albums)')


def build_android():
    dest = ROOT / 'android' / 'app' / 'src' / 'main' / 'assets'
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(DOCS, dest, ignore=shutil.ignore_patterns('CNAME', 'sw.js', '.nojekyll'))
    print(f'copied docs/ -> {dest.relative_to(ROOT)}')


def build_artifact():
    html = (DOCS / 'index.html').read_text(encoding='utf8')
    body = html.split('<!-- app:start -->', 1)[1].split('<!-- app:end -->', 1)[0].strip()
    head = html.split('<head>', 1)[1].split('</head>', 1)[0]
    title = re.search(r'<title>.*?</title>', head).group(0)
    fonts = [l for l in head.splitlines() if 'fonts.g' in l]
    css = (DOCS / 'styles.css').read_text(encoding='utf8')
    data = (DOCS / 'data' / 'albums.js').read_text(encoding='utf8')
    app = (DOCS / 'app.js').read_text(encoding='utf8')
    out = ROOT / 'dist' / 'spin-next-artifact.html'
    out.parent.mkdir(exist_ok=True)
    out.write_text('\n'.join([
        title,
        '<meta name="claude:viewport-fit-sides" content="cover">',
        *fonts,
        '<style>\n' + css + '</style>',
        body,
        '<script>\n' + data + '</script>',
        '<script>\n' + app + '</script>',
    ]) + '\n', encoding='utf8')
    print(f'wrote {out.relative_to(ROOT)}')


if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if what in ('data', 'all'):
        build_data()
    if what in ('android', 'all'):
        build_android()
    if what in ('artifact', 'all'):
        build_artifact()
